    //Cargar tabla
    private void cargarTabla() {
        modeloTabla.setRowCount(0);

        for (Cliente cli : controlador.getListaClientes()) {
            Object fila[] = {

                cli.getIdCliente(),
                cli.getCodigoCliente(),
                cli.getNroDocumento(),

                cli.getNombre() + " "
                + cli.getApPaterno() + " "
                + cli.getApMaterno(),

                cli.getTipoCliente(),
                cli.getPuntosAcumulados(),
                cli.getTelefono(),
                cli.getCorreo(),

                cli.isEstado() ? "Activo" : "Inactivo"
            };
            modeloTabla.addRow(fila);
        }
    }

