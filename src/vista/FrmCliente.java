    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigoCliente.getText();

            if (codigo.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese el código del cliente");
                txtCodigoCliente.requestFocus();
            return;
            }

        Cliente cliente = controlador.buscarCliente(codigo);

        if (cliente == null) {
            JOptionPane.showMessageDialog(this, "Cliente no encontrado");
            return;
        }

        txtIdCliente.setText(String.valueOf(cliente.getIdCliente()));
        txtNroDocumento.setText(cliente.getNroDocumento());
        txtApPaterno.setText(cliente.getApPaterno());
        txtApMaterno.setText(cliente.getApMaterno());
        txtNombre.setText(cliente.getNombre());
        txtTelefono.setText(cliente.getTelefono());
        txtCorreo.setText(cliente.getCorreo());
        txtDireccion.setText(cliente.getDireccion());
        txtPuntosAcumulados.setText(String.valueOf(cliente.getPuntosAcumulados()));

        cmbTipoDocumento.setSelectedItem(cliente.getTipoDocumento());
        cmbSexo.setSelectedItem(cliente.getSexo());
        cmbTipoCliente.setSelectedItem(cliente.getTipoCliente());
        cmbEstadoCliente.setSelectedItem(cliente.isEstado() ? "Activo" : "Inactivo");

        txtCodigoCliente.setEditable(false);

        JOptionPane.showMessageDialog(this, "Cliente encontrado");
    }//GEN-LAST:event_btnBuscarActionPerformed

