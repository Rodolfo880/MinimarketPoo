    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if (txtCodigoCliente.getText().trim().isEmpty()
            || txtNombre.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(
                this,
                "Complete los campos obligatorios"
            );
            return;
        }

        if (!Validaciones.validarDNI(
            txtNroDocumento.getText())) {

                JOptionPane.showMessageDialog(
                this,
                "El DNI debe tener 8 dígitos"
            );
            return;
        }

        if (controlador.existeCodigoCliente(
            txtCodigoCliente.getText())) {

                JOptionPane.showMessageDialog(
                this,
                "El código ya existe"
            );
            return;
        }

        if (controlador.existeDocumentoCliente(
            txtNroDocumento.getText())) {

                JOptionPane.showMessageDialog(
                this,
                "El documento ya existe"
            );
            return;
        }

        Cliente cliente = new Cliente();
        
        cliente.setFechaNacimiento(new java.util.Date());
        cliente.setSexo(cmbSexo.getSelectedItem().toString());
        cliente.setDireccion(txtDireccion.getText());
        cliente.setFechaRegistro(new java.util.Date());
        cliente.setIdCliente(Integer.parseInt(txtIdCliente.getText()));
        cliente.setCodigoCliente(txtCodigoCliente.getText());
        cliente.setTipoDocumento(cmbTipoDocumento.getSelectedItem().toString());
        cliente.setNroDocumento(txtNroDocumento.getText());
        cliente.setApPaterno(txtApPaterno.getText());
        cliente.setApMaterno(txtApMaterno.getText());
        cliente.setNombre(txtNombre.getText());
        cliente.setTelefono(txtTelefono.getText());
        cliente.setCorreo(txtCorreo.getText());
        cliente.setDireccion(txtDireccion.getText());

        
        cliente.setPuntosAcumulados(
           Integer.parseInt(txtPuntosAcumulados.getText()));

        cliente.setTipoCliente(cmbTipoCliente.getSelectedItem().toString());

        cliente.setEstado(cmbEstadoCliente.getSelectedItem()
            .toString().equals("Activo"));

        controlador.registrarCliente(cliente);

        cargarTabla();
        limpiarCampos();

        JOptionPane.showMessageDialog(
            this,
            "Cliente registrado correctamente"
        );
    }//GEN-LAST:event_btnRegistrarActionPerformed

