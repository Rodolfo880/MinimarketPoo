    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigoEmpleado.getText();

        if (codigo.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ingrese el código del empleado");
            txtCodigoEmpleado.requestFocus();
            return;
        }

        Empleado empleado = controlador.buscarEmpleado(codigo);
        if (empleado == null) {
            javax.swing.JOptionPane.showMessageDialog(
            this,
            "Empleado no encontrado");

            txtCodigoEmpleado.requestFocus();

            return;
        }
        txtIdEmpleado.setText(
        empleado.getIdEmpleado());

        cmbTipoDocumento.setSelectedItem(
        empleado.getTipoDocumento());

        txtNroDocumento.setText(
        empleado.getNroDocumento());

        txtApPaterno.setText(
        empleado.getApPaterno());

        txtApMaterno.setText(
        empleado.getApMaterno());

        txtNombre.setText(
        empleado.getNombre());

        txtTelefono.setText(
        empleado.getTelefono());

        txtCorreo.setText(
        empleado.getCorreo());

        txtDireccion.setText(
        empleado.getDireccion());

        txtCargo.setText(
        empleado.getCargo());

        txtSueldo.setText(
        String.valueOf(
        empleado.getSueldo()));

        cmbEstadoEmpleado.setSelectedItem(
                empleado.isEstadoEmpleado()
            ? "Activo"
            : "Inactivo");

        javax.swing.JOptionPane.showMessageDialog(
        this,
        "Empleado encontrado");
        
        txtCodigoEmpleado.setEditable(false);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigoEmpleado.getText();
        if (codigo.trim().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Busque un empleado primero"
            );
            return;
        }

        int opcion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea eliminar este empleado?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );

        if (opcion == JOptionPane.YES_OPTION) {
            boolean eliminado =
                controlador.eliminarEmpleado(codigo);

            if (eliminado) {
                cargarTabla();
                limpiarCampos();
                JOptionPane.showMessageDialog(
                    this,
                    "Empleado eliminado correctamente"
            );

        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Empleado no encontrado");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

