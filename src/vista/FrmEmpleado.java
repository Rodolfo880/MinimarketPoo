    //Cargar tabla
    private void cargarTabla() {

    modeloTabla.setRowCount(0);

    for (Empleado emp : controlador.getListaEmpleados()) {

        Object fila[] = {

            emp.getIdEmpleado(),
            emp.getCodigoEmpleado(),
            emp.getNroDocumento(),
            emp.getNombre() + " " +
            emp.getApPaterno() + " " +
            emp.getApMaterno(),
            emp.getCargo(),
            emp.getSueldo(),
            emp.getTelefono(),
            emp.getCorreo(),
            emp.isEstadoEmpleado() ? "Activo" : "Inactivo"

            };
            modeloTabla.addRow(fila);
        }
    }

