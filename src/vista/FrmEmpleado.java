    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigoEmpleado.getText();
        if (codigo.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Primero busque un empleado"
        );
            return;
        }

        Empleado empleado = new Empleado();
        empleado.setIdEmpleado(
            txtIdEmpleado.getText()
        );

        empleado.setCodigoEmpleado(
            txtCodigoEmpleado.getText()
        );

        empleado.setTipoDocumento(
            cmbTipoDocumento.getSelectedItem().toString()
        );

        empleado.setNroDocumento(
            txtNroDocumento.getText()
        );

        empleado.setApPaterno(
            txtApPaterno.getText()
        );

        empleado.setApMaterno(
            txtApMaterno.getText()
        );

        empleado.setNombre(
            txtNombre.getText()
        );

        empleado.setTelefono(
            txtTelefono.getText()
        );

        empleado.setCorreo(
            txtCorreo.getText()
        );

        empleado.setDireccion(
            txtDireccion.getText()
        );

        empleado.setCargo(
            txtCargo.getText()
        );

        empleado.setSueldo(
            Double.parseDouble(
                    txtSueldo.getText()
            )
        );

        empleado.setEstadoEmpleado(
            cmbEstadoEmpleado.getSelectedItem()
                    .toString()
                    .equals("Activo")
        );
        boolean actualizado =
            controlador.actualizarEmpleado(empleado);

        if (actualizado) {
            cargarTabla();
            limpiarCampos();
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Empleado actualizado correctamente"
        );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
            this,
            "Empleado no encontrado");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

